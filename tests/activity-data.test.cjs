const assert = require('node:assert/strict');
const D = require('../activity-data.js');
const ids = D.jobs.map(job => job.id);
assert.equal(D.encodeResult(ids),'v1.01234567');
assert.deepEqual(D.decodeResult(D.encodeResult([...ids].reverse())),[...ids].reverse());
for(const invalid of [null,undefined,'','v2.01234567','v1.00123456','v1.0123456','v1.012345678','v1.0123456x','<script>','v1.01234567\n']) assert.equal(D.decodeResult(invalid),null);
assert.throws(()=>D.encodeResult(['cashier']));
assert.equal(D.validOrder(ids), true);
assert.equal(D.validOrder([...ids.slice(1),ids[1]]), false);
assert.equal(D.validOrder(ids.slice(1)), false);
assert.equal(D.moveJob(ids,0,7)[7],ids[0]);
assert.deepEqual(D.moveJob(ids,0,-1),ids);
assert.deepEqual(D.moveJob(ids,7,8),ids);
assert.equal(D.moveJob(ids,7,0)[0],ids[7]);
const rows = D.rankJobs([ids,[...ids].reverse()]);
assert.equal(rows.length,8);
assert.ok(rows.every(row=>row.average===4.5 && row.rank===1 && row.tied));
assert.deepEqual(D.rankJobs([]),[]);
const withUser = D.rankJobs([...D.seedOrders.map(s=>s.order),ids]);
assert.equal(withUser[0].total,7);
assert.ok(withUser.every(row=>row.average>=1 && row.average<=8));
assert.deepEqual(D.modes([4,9,9,1]),[1,2]);
assert.equal(D.grade([4,9,9,1],1),true);
assert.equal(D.grade([4,9,9,1],2),true);
assert.equal(D.grade([4,9,9,1],0),false);
assert.equal(D.grade([0,0,0,0],0),null);
assert.deepEqual(D.modes([0,0,0,0]),[]);
const record = {cohort:'young',answers:Object.fromEntries(D.questions.map(q=>[q.id,0]))};
assert.equal(D.validResponse(record),true);
assert.equal(D.validResponse({cohort:'young',answers:{}}),false);
assert.equal(D.validResponse({cohort:'bad',answers:record.answers}),false);
for (const q of D.questions) {
  assert.equal(D.tally(q,'young',record)[0],q.seed.young[0]+1);
  assert.deepEqual(D.tally(q,'older',record),q.seed.older);
  assert.deepEqual(D.tally(q,'young',null),q.seed.young);
  assert.equal(D.tally(q,'young',record).reduce((a,b)=>a+b,0),41);
  const moved={...record,cohort:'older'};
  assert.deepEqual(D.tally(q,'young',moved),q.seed.young);
  assert.equal(D.tally(q,'older',moved).reduce((a,b)=>a+b,0),41);
  for(const cohort of D.cohorts) assert.equal(q.seed[cohort.id].reduce((a,b)=>a+b,0),40);
}
console.log('PASS: valid permutations, reorder boundaries, average rankings, ties, modal scoring, empty samples, deduplicated cohort tally and cohort changes.');